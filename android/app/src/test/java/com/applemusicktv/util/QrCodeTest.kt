package com.applemusicktv.util

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Test

/**
 * Pins [QrCode] to matrices that were verified by decoding them with OpenCV's
 * QRCodeDetector. If a refactor changes the output, these fail — which is the point:
 * a QR code that no longer scans is otherwise invisible until someone points a phone
 * at a TV.
 */
class QrCodeTest {

    private fun render(m: Array<BooleanArray>) =
        m.joinToString("|") { row -> row.joinToString("") { if (it) "1" else "0" } }

    @Test
    fun `encodes a version 2 url`() {
        val expected =
            "1111111000011010001111111|1000001000111101001000001|1011101010010000101011101|" +
            "1011101010000100001011101|1011101010011010001011101|1000001010001011101000001|" +
            "1111111010101010101111111|0000000011100001000000000|1011111001110101101111100|" +
            "1010010100000010010000010|0101011011011111001101011|0011100000110000100010001|" +
            "1101101001111100001110111|1110010000000110000001010|1011111101111101010101011|" +
            "1001010110010001000001001|1001111110011100111110100|0000000010101110100011100|" +
            "1111111000001000101011111|1000001011001001100011011|1011101011100101111111100|" +
            "1011101011111011101110111|1011101010101000010000101|1000001001101000101111001|" +
            "1111111011110101011111111"
        val m = QrCode.encode("http://192.168.1.246:8080")
        assertNotNull(m)
        assertEquals(25, m!!.size)
        assertEquals(expected, render(m))
    }

    @Test
    fun `encodes a version 3 url`() {
        val expected =
            "11111110001110011101001111111|10000010000010000110001000001|10111010110110101010001011101|" +
            "10111010110000001110101011101|10111010110111110101001011101|10000010100001111010001000001|" +
            "11111110101010101010101111111|00000000110001010010000000000|10111110000010110110101111100|" +
            "01111100001000011001001010001|10010111100110000010000110000|11010000100010101011011010010|" +
            "01000111111100001110110101100|00100100001101110101001010101|10101010001011111010011000100|" +
            "00010000101111010011110100010|00111011001010110111010000100|11011000001100011001011011101|" +
            "10111111001100000010001001100|10101001000000101010011010010|10101011101100001010111110111|" +
            "00000000110101110111100011111|11111110010111111101101011100|10000010101111010110100010001|" +
            "10111010101010110000111111111|10111010100111011010010100000|10111010101011000010001011010|" +
            "10000010001100001001110110010|11111110110011101010000001100"
        val m = QrCode.encode("http://192.168.100.200:8080")
        assertNotNull(m)
        assertEquals(29, m!!.size)
        assertEquals(expected, render(m))
    }

    @Test
    fun `returns null when the text is too long for version 6`() {
        assertNull(QrCode.encode("x".repeat(200)))
    }
}
